export interface YamnetRoute {
  target: RoutingTarget;
  childName: string;
  confidence: number;
  yamnetClass: string;
}

/** Classes genéricas demais pra rotear sozinhas (não dizem qual instrumento é).
 * "Percussion" entra aqui apesar de ter rota própria no mapa: testada com áudio real
 * (caixa, bumbo, chimbal), ela dispara mais forte que "Drum"/"Snare drum"/"Hi-hat" para
 * bateria comum de kit — e sem essa exclusão, bateria inteira era roteada pra Percussões
 * em vez de Bateria. Só os instrumentos de percussão de mão têm classe própria específica
 * (Tambourine, Maraca, Bongô etc.) e continuam roteando certo sem precisar de "Percussion".
 * Também ficam de fora "Silence" e os gêneros e climas de música (índices 211 a 276:
 * "Pop music", "Gospel music", "Happy music"...), que não dizem o instrumento. */
const GENERIC_CLASSES = new Set([
  'Music', 'Musical instrument', 'Percussion', 'Silence',
  ...YAMNET_CLASS_NAMES.slice(211, 277).filter((n) => !CATEGORY_MAP[n]),
]);

/** Abaixo disto a IA está só chutando. Num stem o "Music" leva quase toda a nota, então
 * o instrumento certo costuma ficar entre 5% e 40% (medido: voz 7%, bumbo 10%, baixo 60%). */
const MIN_SCORE = 0.05;
/** Fala precisa de mais certeza: plateia e ruído de palco soam como fala para a IA. */
const SPEECH_MIN_SCORE = 0.3;
const SPEECH_CLASSES = new Set(['Speech', 'Narration, monologue']);
/** Voz cantada costuma vir com "Speech" alto (medido: até 48% num stem de voz cantada). Com
 * qualquer sinal de canto, ou com música junto, a fala vira Guia; o Maestro é só fala pura. */
const SINGING_CLASSES = new Set(['Singing', 'Vocal music', 'A capella', 'Child singing', 'Yodeling', 'Humming', 'Rapping', 'Chant', 'Choir']);
const SINGING_HINT = 0.03;
const SPEECH_WITH_MUSIC = 0.3;
/** Trecho quase todo em silêncio (stem vazio): não decide nada. */
const SILENCE_MAX = 0.5;
/** "Wood block", "Plop", "Tick"... também saem de percussão tocada (bloco, cowbell, aro). O click
 * de verdade não tem música (medido: "Music" até 8%); percussão de VS tem (medido: 76% a 84%).
 * Com música junto, ou com bateria ou percussão mais forte que o som de click, é Percussões. */
const CLICK_WITH_MUSIC = 0.3;
const PLAYED_PERCUSSION = new Set(['Percussion', 'Drum', 'Drum kit', 'Snare drum', 'Bass drum', 'Cowbell', 'Rattle (instrument)', 'Maraca', 'Tambourine', 'Shaker']);

/**
 * Converte o resultado bruto do YAMNet (lista de classes com probabilidade, já
 * ordenada da maior pra menor) na faixa/instrumento do VS Stage Pro. Pula as classes
 * genéricas e escolhe o som específico mais forte que tem faixa, desde que ele não fique
 * muito abaixo de um som específico sem faixa (ex.: "Crowd" ganhando de "Speech" = plateia).
 */
export function routeByYamnetScores(
  scores: { className: string; probability: number }[]
): YamnetRoute | null {
  // trecho quase mudo não decide nada, menos o click: ele é silêncio entre um toque e outro
  const silence = scores.find((s) => s.className === 'Silence')?.probability ?? 0;
  const mutedOut = silence >= SILENCE_MAX;
  let strongestUnmapped = 0;
  for (const { className, probability } of scores) {
    if (!GENERIC_CLASSES.has(className) && !CATEGORY_MAP[className]) strongestUnmapped = Math.max(strongestUnmapped, probability);
  }
  for (const { className, probability } of scores) {
    if (GENERIC_CLASSES.has(className)) continue;
    const route = CATEGORY_MAP[className];
    if (!route) continue;
    if (SPEECH_CLASSES.has(className) && probability < SPEECH_MIN_SCORE) continue;
    if (mutedOut && route.target !== 'track-click') return null;
    if (probability < MIN_SCORE || probability < strongestUnmapped * 0.5) return null;
    if (route.target === 'track-click') {
      const music = scores.find((x) => x.className === 'Music')?.probability ?? 0;
      const played = Math.max(0, ...scores.filter((x) => PLAYED_PERCUSSION.has(x.className)).map((x) => x.probability));
      if (music >= CLICK_WITH_MUSIC || played > probability) {
        return { ...PERCUSSION_ROUTE, confidence: probability, yamnetClass: className };
      }
    }
    if (SPEECH_CLASSES.has(className)) {
      const singing = Math.max(0, ...scores.filter((x) => SINGING_CLASSES.has(x.className)).map((x) => x.probability));
      const music = scores.find((x) => x.className === 'Music')?.probability ?? 0;
      if (singing >= SINGING_HINT || music >= SPEECH_WITH_MUSIC) {
        return { ...CATEGORY_MAP.Singing, confidence: probability, yamnetClass: className };
      }
    }
    return { ...route, confidence: probability, yamnetClass: className };
  }
  return null;
}

/**
 * 2º palpite, só para mostrar na conferência das faixas (não muda a decisão): o som específico
 * mais forte, depois do 1º, que vai para outra faixa. Bloco e "Plop" com música junto contam
 * como Percussões, igual ao 1º palpite. null quando não há outro som com faixa.
 */
export function secondYamnetRoute(
  scores: { className: string; probability: number }[],
  first: { target: RoutingTarget } | null
): YamnetRoute | null {
  const music = scores.find((x) => x.className === 'Music')?.probability ?? 0;
  for (const { className, probability } of scores) {
    if (GENERIC_CLASSES.has(className)) continue;
    let route: { target: RoutingTarget; childName: string } | undefined = CATEGORY_MAP[className];
    if (!route) continue;
    if (SPEECH_CLASSES.has(className) && probability < SPEECH_MIN_SCORE) continue;
    if (route.target === 'track-click' && music >= CLICK_WITH_MUSIC) route = PERCUSSION_ROUTE;
    if (first && route.target === first.target) continue;
    if (probability < 0.01) return null;
    return { target: route.target, childName: route.childName, confidence: probability, yamnetClass: className };
  }
  return null;
}

