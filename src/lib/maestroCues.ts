// Busca nas falas prontas: palavras em qualquer ordem, sem acento e sem diferença de maiúscula

export interface ReadyCueHit {
  cue: ReadyCue;
  group: ReadyCueGroup;
  /** Trechos do texto que bateram com a busca ([início, fim) em posições do texto). */
  ranges: Array<[number, number]>;
}

/** Texto sem acento e minúsculo, letra por letra (o mesmo tamanho: as posições servem para destacar). */
function foldChars(text: string): string {
  let out = '';
  for (const ch of text) {
    const f = ch.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
    out += f.length === ch.length ? f : ch;
  }
  return out;
}

/** As palavras de um texto, com a posição de cada uma. */
function wordsOf(folded: string): Array<{ word: string; at: number }> {
  return [...folded.matchAll(/[a-z0-9]+/g)].map((m) => ({ word: m[0], at: m.index ?? 0 }));
}

/** As palavras digitadas na busca. */
export function searchWords(query: string): string[] {
  return wordsOf(foldChars(query)).map((w) => w.word);
}

const numberOf = (word: string) => NUMBER_WORDS[word] ?? word;

/**
 * Falas prontas de todos os assuntos que têm TODAS as palavras da busca, em qualquer ordem. Cada
 * palavra vale pelo começo ("refr" acha "Pré-refrão"); número por extenso acha o algarismo ("dois"
 * acha "Verso 2"); palavra que só bate com o nome do assunto também vale ("culto" mostra o assunto
 * todo). As que batem no texto vêm primeiro, depois as mais curtas.
 */
export function searchReadyCues(query: string, limit = Infinity): ReadyCueHit[] {
  const words = searchWords(query);
  if (!words.length) return [];
  const whole = words.join(' ');
  const found: Array<ReadyCueHit & { score: number; order: number }> = [];
  let order = 0;
  for (const group of READY_CUE_GROUPS) {
    const label = wordsOf(foldChars(group.label));
    for (const cue of group.cues) {
      order++;
      const folded = foldChars(cue.text);
      const tokens = wordsOf(folded);
      const ranges: Array<[number, number]> = [];
      let score = 0;
      let ok = true;
      for (const w of words) {
        let hit = false;
        tokens.forEach((t, i) => {
          if (t.word.startsWith(w)) ranges.push([t.at, t.at + w.length]);
          else if (numberOf(t.word) === numberOf(w)) ranges.push([t.at, t.at + t.word.length]);
          else return;
          if (!hit) score += (i === 0 ? 3 : 2) + (t.word === w ? 1 : 0);
          hit = true;
        });
        if (!hit && !label.some((t) => t.word.startsWith(w))) { ok = false; break; }
      }
      if (!ok) continue;
      if (tokens.map((t) => t.word).join(' ') === whole) score += 10;
      found.push({ cue, group, ranges: mergeRanges(ranges), score, order });
    }
  }
  found.sort((a, b) => b.score - a.score || a.cue.text.length - b.cue.text.length || a.order - b.order);
  return found.slice(0, limit).map(({ cue, group, ranges }) => ({ cue, group, ranges }));
}

function mergeRanges(ranges: Array<[number, number]>): Array<[number, number]> {
  const sorted = [...ranges].sort((a, b) => a[0] - b[0]);
  const out: Array<[number, number]> = [];
  for (const r of sorted) {
    const last = out[out.length - 1];
    if (last && r[0] <= last[1]) last[1] = Math.max(last[1], r[1]);
    else out.push([r[0], r[1]]);
  }
  return out;
}

/** O texto em pedaços, com os trechos que bateram com a busca marcados (para destacar na tela). */
export function highlightParts(text: string, ranges: ReadonlyArray<[number, number]>): Array<{ text: string; match: boolean }> {
  const parts: Array<{ text: string; match: boolean }> = [];
  let at = 0;
  for (const [start, end] of ranges) {
    if (start > at) parts.push({ text: text.slice(at, start), match: false });
    parts.push({ text: text.slice(start, end), match: true });
    at = end;
  }
  if (at < text.length) parts.push({ text: text.slice(at), match: false });
  return parts;
}
